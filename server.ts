async function startServer() {
  const app = express();
  app.use(express.json());

  // Health check endpoint
  app.get('/api/health', (req, res) => {
    res.json({ status: 'ok', time: new Date().toISOString() });
  });

  // CSC AI Chatbot API endpoint
  app.post('/api/csc-chat', async (req, res) => {
    try {
      const { message, conversationHistory = [] } = req.body;

      if (!message || typeof message !== 'string') {
        res.status(400).json({ error: 'Message is required' });
        return;
      }

      const ai = getAI();
      if (!ai) {
        // Fallback intelligent response if Gemini API key is not configured
        res.json({
          reply: generateLocalKnowledgeResponse(message),
          source: 'local_kb'
        });
        return;
      }

      // Build contents array with context
      const formattedContents = [];

      // Add recent conversation history if provided
      if (Array.isArray(conversationHistory)) {
        for (const item of conversationHistory.slice(-4)) {
          if (item && item.role && item.text) {
            formattedContents.push({
              role: item.role === 'user' ? 'user' : 'model',
              parts: [{ text: item.text }]
            });
          }
        }
      }

      // Add current user prompt
      formattedContents.push({
        role: 'user',
        parts: [{ text: message }]
      });

      const response = await ai.models.generateContent({
        model: 'gemini-3.8-flash',
        contents: formattedContents,
        config: {
          systemInstruction: CSC_SYSTEM_INSTRUCTION,
          temperature: 0.7,
        },
      });

      const replyText = response.text || 'माफ़ करें, जानकारी प्राप्त नहीं हो सकी। कृपया सीधे कॉल या व्हाट्सएप 7903027843 पर संपर्क करें।';
      res.json({ reply: replyText, source: 'gemini' });
    } catch (error: any) {
      console.error('CSC Chat API Error:', error);
      // If error occurs with API, respond gracefully with local knowledge
      const localReply = generateLocalKnowledgeResponse(req.body.message || '');
      res.json({
        reply: localReply,
        source: 'local_fallback',
        errorInfo: error.message ? String(error.message).slice(0, 100) : undefined
      });
    }
  });

  // Vite middleware for dev or static serving for prod
  if (process.env.NODE_ENV !== 'production') {
    const vite = await createViteServer({
      server: { middlewareMode: true },
      appType: 'spa',
    });
    app.use(vite.middlewares);
  } else {
    const distPath = path.join(process.cwd(), 'dist');
    app.use(express.static(distPath));
    app.get('*', (req, res) => {
      res.sendFile(path.join(distPath, 'index.html'));
    });
  }

  app.listen(PORT, '0.0.0.0', () => {
    console.log(`Server running on http://0.0.0.0:${PORT}`);
  });
}

